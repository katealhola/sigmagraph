"""Build a standalone application on the current macOS or Linux host."""
import argparse
import os
import platform
import struct
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'dist')
    parser.add_argument('--work',type=Path,default=ROOT/'.build')
    args=parser.parse_args()
    if sys.platform not in ('darwin','linux'):
        parser.error('This build script targets macOS and Linux.')
    source=ROOT
    from sigmagraph import __version__
    work=args.work.resolve();work.mkdir(parents=True,exist_ok=True)
    os.environ.setdefault('PYINSTALLER_CONFIG_DIR',str(work/'cache'))
    from scripts.collect_licenses import collect
    licenses=work/'licenses';collect(licenses)
    icon=None
    if sys.platform=='darwin':
        os.environ.setdefault('QT_QPA_PLATFORM','offscreen')
        from sigmagraph.app import create_application,app_icon
        app=create_application(['build-icon'])
        asset_dir=work/'assets';asset_dir.mkdir(exist_ok=True)
        chunks=[]
        for tag,size in [('icp4',16),('icp5',32),('icp6',64),('ic07',128),('ic08',256),('ic09',512),('ic10',1024)]:
            p=asset_dir/f'icon{size}.png';app_icon(size).pixmap(size,size).save(str(p))
            data=p.read_bytes();chunks.append(tag.encode()+struct.pack('>I',len(data)+8)+data)
        body=b''.join(chunks);icon=asset_dir/'SigmaGraph.icns'
        icon.write_bytes(b'icns'+struct.pack('>I',len(body)+8)+body)
    spec=work/'SigmaGraph.spec'
    bundle=f'''app = BUNDLE(coll, name='SigmaGraph.app', icon={str(icon)!r}, bundle_identifier='app.sigmagraph.editor',
    info_plist={{'CFBundleShortVersionString':{__version__!r},'NSHighResolutionCapable':True,
      'LSMinimumSystemVersion':'14.0','CFBundleDocumentTypes':[{{'CFBundleTypeName':'SigmaStudio DSP Project',
      'CFBundleTypeExtensions':['dspproj','sgproj'],'CFBundleTypeRole':'Editor'}}]}})
''' if sys.platform=='darwin' else ''
    spec.write_text(f'''# Generated by scripts/build_app.py; paths point to this source checkout.
a = Analysis([{str(source/'run.py')!r}], pathex=[{str(source)!r}], binaries=[], datas=[({str(source/'sigmagraph'/'data')!r},'sigmagraph/data'),({str(licenses)!r},'licenses'),({str(source/'README.md')!r},'.')], hiddenimports=[],
    hookspath=[], hooksconfig={{}}, runtime_hooks=[], excludes=['PySide6.QtWebEngineCore','PySide6.QtWebEngineWidgets',
    'PySide6.QtQml','PySide6.QtQuick','PySide6.QtMultimedia','PySide6.QtPdf','PySide6.QtNetwork'])
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='SigmaGraph', debug=False, bootloader_ignore_signals=False,
    strip=False, upx=False, console=False, icon={str(icon)!r})
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name='SigmaGraph')
{bundle}
''')
    import PyInstaller.__main__
    PyInstaller.__main__.run(['--noconfirm','--clean','--distpath',str(args.output.resolve()),
                              '--workpath',str(work/'objects'),str(spec)])
    print(f'Built for {platform.system()} {platform.machine()}: {args.output.resolve()}')


if __name__=='__main__':main()
