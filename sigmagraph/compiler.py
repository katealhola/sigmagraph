"""Independent ADAU1701 graph compiler, using recovered Sigma100 instructions.

Data RAM shifts one position per frame. Every signal has a three-word history;
double-precision feedback retains the lower accumulator word separately. NOPs
separate dependent writes, avoiding the vendor compiler's pipeline hazards.
"""
from __future__ import annotations
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import tempfile
import os
from .dsp import DSPError,checked,sections,topological,delay_samples,finite
from .assembler1701 import assemble
from .codec1701 import encode_q523
from . import __version__

@dataclass
class Compilation:
    program: bytes
    parameters: bytes
    assembly: str
    parameter_map: list
    allocation: list
    instructions: int
    data_words: int
    sample_rate: float
    project_name: str

    @property
    def resources(self):
        return {'program_instructions':self.instructions,'program_capacity':1024,
                'parameter_words':len(self.parameter_map),'parameter_capacity':1024,
                'data_words':self.data_words,'data_capacity':2048}

    def export(self,directory):
        """Publish a new build directory atomically; an existing build is kept."""
        directory=Path(directory).expanduser().resolve()
        if directory.exists(): raise DSPError('Build directory already exists. Choose a new directory to retain the previous build.')
        directory.parent.mkdir(parents=True,exist_ok=True)
        with tempfile.TemporaryDirectory(dir=directory.parent,prefix='.sigmagraph-build-') as temp:
            root=Path(temp)/'build';root.mkdir()
            blobs={'program.bin':self.program,'parameters.bin':self.parameters,
                   'program.asm':self.assembly.encode(),
                   'parameters.json':(json.dumps(self.parameter_map,indent=2)+'\n').encode(),
                   'memory.json':(json.dumps(self.allocation,indent=2)+'\n').encode()}
            header=['/* Generated by SigmaGraph '+__version__+'. Raw RAM images; configure the board separately. */',
                    '#ifndef SIGMAGRAPH_DSP_H','#define SIGMAGRAPH_DSP_H','#include <stdint.h>',
                    '#define SIGMAGRAPH_PROGRAM_ADDRESS 0x0400',
                    '#define SIGMAGRAPH_PARAMETER_ADDRESS 0x0000']
            for name,blob in [('sigmagraph_program',self.program),('sigmagraph_parameters',self.parameters)]:
                header.append(f'static const uint8_t {name}[{len(blob)}] = {{')
                header.extend('  '+', '.join(f'0x{x:02x}' for x in blob[i:i+20])+',' for i in range(0,len(blob),20))
                header.append('};')
            header.append('#endif')
            blobs['dsp.h']=('\n'.join(header)+'\n').encode()
            manifest={'format':'SigmaGraph ADAU1701 build','compiler_version':__version__,
                      'project':self.project_name,'target':'ADAU1701','sample_rate':self.sample_rate,
                      'resources':self.resources,'hardware_verified':False,
                      'images':[{'file':'program.bin','word_address':1024,'word_bytes':5,'words':1024},
                                {'file':'parameters.bin','word_address':0,'word_bytes':4,'words':1024}],
                      'sha256':{name:hashlib.sha256(data).hexdigest() for name,data in blobs.items()},
                      'integration':['Configure external clock, serial I/O, DACs and GPIO for the board.',
                                     'Stop and reset/clear DSP state before loading these RAM images.',
                                     'Write program and parameter images using their word addresses and widths.',
                                     'Start the core only after the board configuration and RAM writes finish.'],
                      'limits':['Experimental independent compiler; no hardware validation yet.',
                                'No USBi transport, EEPROM self-boot image or hardware register configuration.',
                                'Delay allocation is fixed at compile time. Increasing delay requires recompiling.']}
            blobs['manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
            for name,data in blobs.items(): (root/name).write_bytes(data)
            os.rename(root,directory)
        return directory


class Backend:
    def __init__(self,project):
        self.project=project;self.lines=[];self.params=[];self.data=2
        self.allocations=[{'name':'ADC staging','address':0,'words':2}];self.signals={}

    def alloc(self,name,words=3):
        if self.data+words>2048: raise DSPError(f'Data RAM exhausted at {name}: {self.data+words} / 2048 words.')
        base=self.data;self.data+=words
        self.allocations.append({'name':name,'address':base,'words':words})
        return base+words-1

    def param(self,node,suffix,value,integer=False):
        address=len(self.params)
        if address>=1024: raise DSPError('Parameter RAM exceeds 1024 words.')
        data=int(value).to_bytes(4,'big') if integer else encode_q523(value)
        self.params.append({'name':node.algorithm+suffix,'node':node.id,'cell':node.label,
                            'address':address,'value':value,'encoding':'integer' if integer else '5.23',
                            'data_hex':data.hex()})
        return 512+address

    def emit(self,line): self.lines.append(line)
    def mac(self,coeff,data,add=False,subtract=False,mux=None):
        self.emit(f"accum0 = {mux or ('accum0' if add else '0')} {'-' if subtract else '+'} coeff[{coeff}]*data[{data}];")
    def store(self,address,mux='accum0'):
        self.emit('nop');self.emit(f'data[{address}] = {mux};');self.emit('nop');self.emit('nop')
    def copy(self,src,dst,coeff=264): self.mac(coeff,src);self.store(dst)

    def cascade(self,node,src,branch=0):
        chain=sections(node,branch)
        if not chain:return src
        if node.kind=='crossover' and branch==0:
            inverted=bool(node.ui.get('S0.R0.InvertLow',False))
            polarity=self.param(node,'LowInvert',-1. if inverted else 1.)
            buffer=self.alloc(node.label+' / low polarity')
            self.copy(src,buffer,polarity);src=buffer
            if inverted:chain[0]=[-v if j<3 else v for j,v in enumerate(chain[0])]
        for i,values in enumerate(chain):
            b0,b1,b2,a1,a2=values
            suffixes=[f'0B{i+1}',f'1B{i+1}',f'2B{i+1}',f'1A{i+1}',f'2A{i+1}']
            if node.kind=='crossover': suffixes=[f'{s}_{branch*2+i}' for s in ['B0','B1','B2','A1','A2']]
            if node.kind=='first_order':suffixes=['01','11','unusedB2','21','unusedA2']
            cs=[self.param(node,s,v) for s,v in zip(suffixes,values)]
            out=self.alloc(f'{node.label} / branch {branch+1} / section {i+1} high')
            low=self.alloc(f'{node.label} / branch {branch+1} / section {i+1} low')
            self.mac(cs[3],low-1)
            self.mac(cs[4],low-2,add=True)
            self.mac(cs[3],out-1,mux='accum0_shiftright23')
            self.mac(cs[4],out-2,add=True)
            for c,d in zip(cs[:3],[src,src-1,src-2]):self.mac(c,d,add=True)
            self.store(out);self.store(low,'accum0_shiftleft23')
            src=out
        return src

    def run(self):
        p=self.project
        if p.target!='ADAU1701': raise DSPError('Compilation currently targets ADAU1701 only.')
        if not p.nodes: raise DSPError('Add an input and output before compiling.')
        issues=p.issues()
        if issues: raise DSPError('\n'.join(issues))
        if {n.fs for n in p.nodes.values()} not in ({44100},{48000}):
            raise DSPError('Use one consistent sample rate: 44100 or 48000 Hz.')
        order=topological(p)
        errors=[]
        for node in order:
            try:
                checked(node)
                if node.kind in ('peq','filter','first_order','biquad','crossover'):
                    for i in range(2 if node.kind=='crossover' else 1):sections(node,i)
                if any(port.signal!=0 or port.data!=1 for port in node.ports): raise DSPError('Only audio signal ports are supported.')
            except (ValueError,OverflowError) as exc:errors.append(f'{node.label}: {exc}')
        if errors: raise DSPError('\n'.join(errors))
        inputs=[n for n in order if n.kind=='input']
        outputs=[n for n in order if n.kind=='output']
        if len(inputs)!=1 or not 1<=len(inputs[0].outputs)<=2 or inputs[0].inputs:
            raise DSPError('Use one ADC input block with ADC 0 and optionally ADC 1. Serial digital inputs are not yet supported.')
        if not outputs: raise DSPError('Connect at least one audio output.')
        adc=inputs[0]
        if adc.properties.get('ins',list(range(len(adc.outputs))))!=list(range(len(adc.outputs))):
            raise DSPError('ADC input ports must be in contiguous channel order starting at 0.')
        for i,port in enumerate(adc.outputs):
            self.emit('nop');self.emit(f'data[{i}] = ser_port;')
        self.emit('nop');self.emit('nop')
        for i,port in enumerate(adc.outputs):
            address=self.alloc(f'{adc.label} / {port.label}')
            self.copy(i,address);self.signals[(adc.id,port.id)]=address
        incoming={(e.target_node,e.target_port):(e.source_node,e.source_port) for e in p.connections.values()}
        used_outputs=set()
        for node in order:
            if node.kind=='input':continue
            ins=[self.signals[incoming[(node.id,port.id)]] for port in node.inputs]
            outs=node.outputs
            self.emit('// '+node.label.replace('\n',' ').replace('\r',' '))
            if node.kind=='output':
                if len(ins)!=1 or outs: raise DSPError(f'{node.label}: output requires one audio input.')
                channel=str(node.properties.get('selectedchannel','DAC0'))
                channels={**{f'DAC{i}':8+i for i in range(4)},**{f'DIG{i}':i for i in range(8)}}
                if channel not in channels: raise DSPError(f'{node.label}: unknown hardware output {channel}.')
                if channel in used_outputs: raise DSPError(f'{channel} has multiple output blocks. Choose distinct hardware channels.')
                used_outputs.add(channel);self.mac(264,ins[0]);self.emit('nop')
                self.emit(f'digout[{channels[channel]}] = accum0;');self.emit('nop');continue
            if not ins or not outs: raise DSPError(f'{node.label}: algorithm requires connected audio inputs and outputs.')
            if node.kind=='gain':
                if len(ins)!=len(outs):raise DSPError(f'{node.label}: volume needs matching input/output channels.')
                if node.enabled:
                    target=self.param(node,'target',10**(finite(node.properties.get('gain',0),'Gain')/20))
                    step=finite(node.properties.get('step',12),'Slew step')
                    if not 0<=step<=23: raise DSPError('Slew step must be from 0 to 23.')
                    slew=self.param(node,'step',2**(-step))
                    current=self.alloc(node.label+' / slew high',2);low=self.alloc(node.label+' / slew low',2)
                    difference=self.alloc(node.label+' / difference',1)
                    self.mac(target,8190);self.mac(264,current-1,add=True,subtract=True);self.store(difference)
                    self.mac(264,low-1);self.mac(264,current-1,mux='accum0_shiftright23')
                    self.mac(slew,difference,add=True);self.store(current);self.store(low,'accum0_shiftleft23')
                    self.emit(f'yreg = data[{current}];');self.emit('nop');self.emit('nop')
                for src,port in zip(ins,outs):
                    dst=self.alloc(node.label+' / '+port.label)
                    self.copy(src,dst,2047 if node.enabled else 264);self.signals[node.id,port.id]=dst
                continue
            if node.kind in ('peq','filter','first_order','biquad','crossover'):
                if len(ins)!=1 or len(outs)!=(2 if node.kind=='crossover' else 1):raise DSPError(f'{node.label}: unsupported filter port configuration.')
                for i,port in enumerate(outs):self.signals[node.id,port.id]=self.cascade(node,ins[0],i)
                continue
            if len(outs)!=1: raise DSPError(f'{node.label}: expected one output.')
            dst=self.alloc(node.label+' / output')
            if node.kind=='delay':
                if len(ins)!=1:raise DSPError(f'{node.label}: use one mono delay per channel.')
                n=delay_samples(node) if node.enabled else 0
                if n:
                    end=self.alloc(node.label+' / delay buffer',n+1);base=end-n
                    param=self.param(node,'',n,integer=True)
                    self.emit(f'xreg = coeff[{param}];');self.emit('nop');self.emit('nop')
                    self.copy(base,dst);self.mac(264,ins[0]);self.store(f'{base} + xreg')
                else:self.copy(ins[0],dst)
            elif node.kind in ('add','subtract'):
                self.mac(264,ins[0])
                for src in ins[1:]:self.mac(264,src,add=True,subtract=node.kind=='subtract')
                self.store(dst)
            elif node.kind=='invert':
                if len(ins)!=1:raise DSPError(f'{node.label}: expected one input.')
                self.mac(264,ins[0],subtract=node.enabled);self.store(dst)
            else:raise DSPError(f'{node.label}: unsupported algorithm.')
            self.signals[node.id,outs[0].id]=dst
        text='\n'.join(self.lines)+'\n'
        count=sum(1 for line in self.lines if not line.startswith('//'))
        if count>1024:raise DSPError(f'Program RAM exhausted: {count} / 1024 instructions. Reduce filter sections or blocks.')
        program=assemble(text,pad_to=1024)
        parameters=b''.join(bytes.fromhex(r['data_hex']) for r in self.params).ljust(4096,b'\0')
        return Compilation(program,parameters,text,self.params,self.allocations,count,self.data,p.sample_rate,p.name)

def compile_project(project):
    try:return Backend(project).run()
    except (OverflowError,KeyError,TypeError) as exc:raise DSPError('Invalid DSP settings or graph: '+str(exc)) from exc

def main():
    import argparse
    from .persistence import load_project
    parser=argparse.ArgumentParser(description='Compile a .dspproj or .sgproj to ADAU1701 RAM images without Qt.')
    parser.add_argument('project',type=Path)
    parser.add_argument('-o','--output',type=Path,required=True,help='New build directory (must not already exist)')
    args=parser.parse_args()
    try:
        build=compile_project(load_project(args.project));build.export(args.output)
    except (ValueError,OSError) as exc:parser.exit(1,str(exc)+'\n')
    print(json.dumps({'output':str(args.output.resolve()),**build.resources},indent=2))

if __name__=='__main__':main()
